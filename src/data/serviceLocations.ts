export function getLocationBySlug(slug: string): SublocationInfo {
  // Normalize slug
  const cleanSlug = slug.toLowerCase().replace(/^(home-x-ray-|home-ecg-)/, "").replace(/-in-/, "-");
  
  if (locationDatabase[cleanSlug]) {
    return locationDatabase[cleanSlug];
  }
  
  if (locationDatabase[slug]) {
    return locationDatabase[slug];
  }

  // Fallback programmatic generation for any unspecified sublocation
  const formattedTitle = slug
    .replace(/^home-x-ray-in-/, "")
    .replace(/^home-x-ray-/, "")
    .split("-")
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ");

  return {
    slug,
    name: `${formattedTitle}`,
    region: "Delhi NCR",
    dispatchHub: "Nearest NCR Mobile Dispatch Hub",
    eta: "30 - 45 Mins",
    landmarks: [`${formattedTitle} Main Market`, "Metro Connectivity Hub", "Central Enclave"],
    nearbyHospitals: ["Max Healthcare", "Fortis Hospital", "Apollo Hospital", "Local Multi-Speciality Centers"],
    description: `Professional portable digital X-ray and 12-lead ECG diagnostics provided directly to patient homes in ${formattedTitle}. Our certified radiographers arrive equipped with low-radiation AERB-approved equipment for gentle, painless bedside imaging.`,
    commonRequests: [
      `Bedside Chest X-Ray in ${formattedTitle}`,
      "12-Lead Digital ECG at Home",
      "Fall Injury / Hip & Knee X-Ray",
      "Cervical & Lumbar Spine Scan",
    ],
  };
}

